def engine_overlays(disabled=None):
    """Merge the ENABLED engine byte-patch modules into {iso_path: [(off, bytes)]}.

    `disabled` defaults to patch_registry's effective disable set (config +
    LANG3_DISABLE env). With nothing disabled this is byte-identical to merging
    every ENGINE_MODULE_DICTS value.
    """
    disabled = disabled_modules() if disabled is None else set(disabled)
    merged: dict[str, list] = {}
    for name, module in ENGINE_MODULE_DICTS.items():
        if name in disabled:
            continue
        for path, edits in module.items():
            merged.setdefault(path, []).extend(edits)
    return merged

