# Output naming — ONE rule, fully derived from git state (no flags):
#   HEAD exactly at the latest tag → "Langrisser III ({lang} v<TAG>).cue"
#     (clean release name; to reproduce: git checkout v0.6 && python3 build.py)
#   anything else → "Langrisser III ({lang} v<TAG>+<branch>).cue"
#     ('+' = work past the release; the branch says WHICH work — e.g.
#     "v0.6+new-ui-patch". Detached HEAD → "v0.6+detached".)
# If git is unavailable (release source archive), the stamped VERSION
# artifact gives the clean name; with neither, the bare language name.
def _git_branch() -> str:
    import subprocess
    try:
        branch = subprocess.check_output(
            ['git', 'rev-parse', '--abbrev-ref', 'HEAD'],
            cwd=str(SCRIPT_DIR), stderr=subprocess.DEVNULL,
        ).decode().strip()
        return 'detached' if branch == 'HEAD' else branch
    except Exception:
        return 'unknown'


def _read_version_artifact() -> str | None:
    """Return the version string stamped in the tracked VERSION file, or None.

    VERSION is the release artifact (written by tools/stamp_version.py at
    release time) that carries the version into builds with no `.git` —
    e.g. a GitHub source archive, where `git describe` cannot run.
    """
    try:
        ver = (SCRIPT_DIR / 'VERSION').read_text(encoding='utf-8').strip().lstrip('v')
        return ver or None
    except Exception:
        return None


def _resolve_canonical_cue_name(lang_display: str) -> str:
    """Derive a clean release filename from git state, then the VERSION artifact.

    If HEAD == latest tag → "Langrisser III ({lang} v<TAG>).cue".
    Else → "Langrisser III ({lang} v<TAG>+<branch>).cue" — '+' marks work
    past the release, the branch names which line of work.
    If git is unavailable (e.g. a release source archive with no `.git`),
    fall back to the stamped VERSION file →
        "Langrisser III ({lang} v<VERSION>).cue".
    If neither git nor VERSION resolves → "Langrisser III ({lang}).cue".
    """
    import subprocess
    try:
        latest_tag = subprocess.check_output(
            ['git', 'describe', '--tags', '--abbrev=0'],
            cwd=str(SCRIPT_DIR), stderr=subprocess.DEVNULL,
        ).decode().strip()
        head_tag = subprocess.check_output(
            ['git', 'tag', '--points-at', 'HEAD'],
            cwd=str(SCRIPT_DIR), stderr=subprocess.DEVNULL,
        ).decode().strip().splitlines()
        ver = latest_tag.lstrip('v')
        if latest_tag in head_tag:
            return f'Langrisser III ({lang_display} v{ver}).cue'
        # Work past the release: "+<branch>" names exactly which line of
        # work produced this build (e.g. "v0.6+new-ui-patch").
        return f'Langrisser III ({lang_display} v{ver}+{_git_branch()}).cue'
    except Exception:
        pass
    # git unavailable — use the release-stamped VERSION artifact.
    ver = _read_version_artifact()
    if ver:
        return f'Langrisser III ({lang_display} v{ver}).cue'
    return f'Langrisser III ({lang_display}).cue'

